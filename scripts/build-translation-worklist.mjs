import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { readJsonFile } from "./lib/json-file.mjs";

const cwd = process.cwd();
const generatedAt = new Date().toISOString().slice(0, 10);
const checkOnly = process.argv.includes("--check");

const directories = [
  {
    title: "Shared UI strings",
    relativeDir: "src/data/ui-copy",
  },
  {
    title: "Conversation entry content",
    relativeDir: "src/data/conversation-content",
  },
  {
    title: "Static trust pages",
    relativeDir: "src/data/static-pages",
  },
];

function getMissingKeys(baseValue, compareValue, prefix = "") {
  return Object.entries(baseValue).flatMap(([key, value]) => {
    const nextKey = prefix ? `${prefix}.${key}` : key;
    const compareEntry = compareValue?.[key];

    if (Array.isArray(value)) {
      return Array.isArray(compareEntry) && compareEntry.length > 0 ? [] : [nextKey];
    }

    if (value && typeof value === "object") {
      return getMissingKeys(value, compareEntry ?? {}, nextKey);
    }

    return compareEntry === undefined ? [nextKey] : [];
  });
}

async function collectMissingByLanguage() {
  const missingByLanguage = new Map();

  for (const directory of directories) {
    const directoryPath = path.join(cwd, directory.relativeDir);
    const files = (await readdir(directoryPath)).filter((name) => name.endsWith(".json"));
    const baseDocument = await readJsonFile(path.join(directoryPath, "en.json"));

    for (const fileName of files) {
      if (fileName === "en.json") {
        continue;
      }

      const languageCode = fileName.replace(/\.json$/, "");
      const document = await readJsonFile(path.join(directoryPath, fileName));
      const missingKeys = getMissingKeys(baseDocument, document);

      if (!missingByLanguage.has(languageCode)) {
        missingByLanguage.set(languageCode, []);
      }

      missingByLanguage.get(languageCode).push({
        missingKeys,
        title: directory.title,
      });
    }
  }

  return missingByLanguage;
}

function buildMarkdown(missingByLanguage) {
  const lines = [
    "# Translation Worklist",
    "",
    `Generated: ${generatedAt}`,
    "",
    "This file is generated by `npm run build:translation-worklist`.",
    "",
  ];

  for (const [languageCode, sections] of [...missingByLanguage.entries()].sort()) {
    const totalMissing = sections.reduce(
      (sum, section) => sum + section.missingKeys.length,
      0,
    );

    lines.push(`## ${languageCode}`);
    lines.push("");
    lines.push(`Total missing keys: ${totalMissing}`);
    lines.push("");

    for (const section of sections) {
      lines.push(`### ${section.title}`);
      lines.push("");

      if (section.missingKeys.length === 0) {
        lines.push("- Complete");
        lines.push("");
        continue;
      }

      for (const key of section.missingKeys) {
        lines.push(`- ${key}`);
      }

      lines.push("");
    }
  }

  return `${lines.join("\n")}\n`;
}

const outputPath = path.join(cwd, "docs/translation_worklist.md");
const missingByLanguage = await collectMissingByLanguage();
const markdown = buildMarkdown(missingByLanguage);

if (checkOnly) {
  const existing = await readFile(outputPath, "utf8").catch(() => null);

  if (existing !== markdown) {
    console.log("docs/translation_worklist.md is out of date.");
    console.log("Run: npm run build:translation-worklist");
    process.exit(1);
  }

  console.log("docs/translation_worklist.md is up to date.");
} else {
  await writeFile(outputPath, markdown, "utf8");
  console.log(`Wrote ${path.relative(cwd, outputPath)}`);
}
